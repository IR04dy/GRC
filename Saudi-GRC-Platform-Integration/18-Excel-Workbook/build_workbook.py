HEADER_FILL = PatternFill('solid', start_color='062E2E')  # primary
HEADER_FONT = Font(bold=True, color='FFFFFF', size=11)
EXAMPLE_FILL = PatternFill('solid', start_color='F0F2F4')
EXAMPLE_FONT = Font(italic=True, color='4A5258')
BORDER = Border(*(Side(style='thin', color='D6DADD') for _ in range(4)))
WRAP = Alignment(wrap_text=True, vertical='top')


def add_sheet(wb: Workbook, name: str, columns: list[tuple[str, bool]],
              dropdowns: dict[str, list[str]], example: list, data_rows: list[list]):
    """Append a sheet with the standard layout.

    columns: [(name, mandatory)]
    dropdowns: {column_name: [allowed values]}
    example: [example row matching columns]
    data_rows: list of row lists matching columns
    """
    if name in wb.sheetnames:
        del wb[name]
    ws = wb.create_sheet(title=name[:31])

    # Header row
    for idx, (col_name, mand) in enumerate(columns, start=1):
        cell = ws.cell(row=1, column=idx)
        cell.value = ('* ' if mand else '') + col_name
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        cell.border = BORDER

    # Example row
    for idx, value in enumerate(example, start=1):
        cell = ws.cell(row=2, column=idx)
        cell.value = value
        cell.font = EXAMPLE_FONT
        cell.fill = EXAMPLE_FILL
        cell.alignment = WRAP
        cell.border = BORDER

    # Data rows
    for r_idx, row in enumerate(data_rows, start=3):
        for c_idx, value in enumerate(row, start=1):
            cell = ws.cell(row=r_idx, column=c_idx)
            cell.value = value
            cell.alignment = WRAP
            cell.border = BORDER

    # Auto width + freeze + filter
    for col_idx, (col_name, _) in enumerate(columns, start=1):
        letter = get_column_letter(col_idx)
        sample = [col_name] + [str(example[col_idx - 1]) if col_idx - 1 < len(example) else '']
        sample += [str(r[col_idx - 1]) if col_idx - 1 < len(r) else '' for r in data_rows]
        width = min(60, max(12, max(len(s) for s in sample) + 2))
        ws.column_dimensions[letter].width = width
    ws.row_dimensions[1].height = 28
    ws.freeze_panes = 'A2'
    last_letter = get_column_letter(len(columns))
    ws.auto_filter.ref = f'A1:{last_letter}{max(3, 2 + len(data_rows))}'

    # Dropdowns
    for col_idx, (col_name, _) in enumerate(columns, start=1):
        if col_name in dropdowns:
            allowed = ','.join(f'"{v}"' if ',' in v else v for v in dropdowns[col_name])
            dv = DataValidation(type='list', formula1=f'"{",".join(dropdowns[col_name])}"', allow_blank=True, showErrorMessage=True)
            dv.error = f'Value must be one of: {", ".join(dropdowns[col_name])}'
            dv.errorTitle = f'{col_name} - invalid'
            letter = get_column_letter(col_idx)
            dv.add(f'{letter}2:{letter}1048576')
            ws.add_data_validation(dv)

    return ws


