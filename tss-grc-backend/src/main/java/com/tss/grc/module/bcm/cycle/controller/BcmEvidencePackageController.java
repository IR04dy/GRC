package com.tss.grc.module.bcm.cycle.controller;

import com.tss.grc.module.bcm.cycle.service.BcmEvidencePackageService;
import com.tss.grc.module.bcm.cycle.service.BcmEvidencePackageService.EvidencePackage;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.web.bind.annotation.*;

/**
 * REST surface for the BCM Audit Evidence Package.
 * <pre>
 *   GET /api/v1/bcm/cycles/{cycleId}/evidence-package
 *     → application/zip download containing all approved BCM artefacts
 *       for the cycle (BIAs · risks · strategies · gaps · CAPAs ·
 *       compliance matrix · audit log) plus a cover sheet and SHA-256
 *       manifest. See {@link BcmEvidencePackageService} for the full
 *       content list.
 * </pre>
 *
 * <p>Requires authentication. The "generated by" name on the cover sheet
 * pulls from the current Spring Security principal — never trust the
 * client to send it, otherwise the audit trail is meaningless.
 */
@RestController
@RequestMapping("/api/v1/bcm/cycles")
@RequiredArgsConstructor
@Tag(name = "BCM Audit Evidence Package")
public class BcmEvidencePackageController {

    private final BcmEvidencePackageService service;

    @GetMapping("/{cycleId}/evidence-package")
    // The evidence ZIP is the most sensitive export on the platform (full BIA / risk /
    // strategy / gap / CAPA / compliance-matrix / audit-log dump for the cycle). Gate it
    // with the same BCM permission as every other BCM export (BcpPlan/CrisisEvent),
    // not a bare isAuthenticated() — otherwise any authenticated user in any role can pull it.
    //
    // F2-27: that permission is now BCM:EXPORT, not BCM:READ. This endpoint is the clearest
    // illustration of the finding — its author reasoned explicitly about sensitivity, called
    // it the most sensitive export on the platform, and still reached for READ, because at
    // the time EXPORT enforced nothing anywhere in the codebase and so did not read as a real
    // option. Access-preserving: all 17 roles holding BCM:READ also hold BCM:EXPORT.
    @PreAuthorize("hasPermission('BCM','EXPORT')")
    public ResponseEntity<ByteArrayResource> download(@PathVariable Long cycleId) {
        EvidencePackage pkg = service.generate(cycleId, currentPrincipalName());
        ByteArrayResource body = new ByteArrayResource(pkg.bytes());
        return ResponseEntity.ok()
            .contentType(MediaType.APPLICATION_OCTET_STREAM)
            .contentLength(pkg.bytes().length)
            .header(HttpHeaders.CONTENT_DISPOSITION,
                "attachment; filename=\"" + pkg.filename() + "\"")
            .body(body);
    }

    /**
     * Resolve the current user's name for the cover sheet. Falls back to
     * {@code "system"} if no security context is available (background
     * scheduler invocations, for example).
     */
    private static String currentPrincipalName() {
        Authentication auth = SecurityContextHolder.getContext().getAuthentication();
        if (auth == null || auth.getName() == null) return "system";
        return auth.getName();
    }
}
