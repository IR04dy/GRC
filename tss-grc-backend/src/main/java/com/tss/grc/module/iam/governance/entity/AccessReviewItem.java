package com.tss.grc.module.iam.governance.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.Where;

import java.time.LocalDateTime;

/**
 * RBAC Access-Governance P2 (plan §6.5) — one campaign review item: a snapshot of a
 * user↔role assignment awaiting CERTIFY / REVOKE / MODIFY (REVOKE auto-executes).
 * Rows are generated by native insert-select; plain entity (no BaseEntity columns).
 */
@Entity
@Table(schema = "iam", name = "access_review_items")
@Where(clause = "is_deleted = 0")
@Getter @Setter @NoArgsConstructor
public class AccessReviewItem {

    @Id @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "organisation_id", nullable = false) private Long organisationId;
    @Column(name = "campaign_id", nullable = false) private Long campaignId;
    @Column(name = "user_id", nullable = false) private Long userId;
    @Column(nullable = false, length = 100) private String username;
    @Column(name = "role_id", nullable = false) private Long roleId;
    @Column(name = "role_name", nullable = false, length = 100) private String roleName;
    @Column(name = "assignment_source", length = 20) private String assignmentSource;
    @Column(name = "valid_to") private LocalDateTime validTo;
    /** PENDING | CERTIFY | REVOKE | MODIFY. */
    @Column(nullable = false, length = 15) private String decision = "PENDING";
    @Column(name = "decided_by") private Long decidedBy;
    @Column(name = "decided_at") private LocalDateTime decidedAt;
    @Column(length = 500) private String note;
    @Column(name = "is_deleted", nullable = false) private Boolean isDeleted = false;
    @Column(name = "created_at", nullable = false, updatable = false, insertable = false)
    private LocalDateTime createdAt;
}
