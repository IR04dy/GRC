package com.tss.grc.module.reporting.service;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.pdf.PdfPTable;

/**
 * Export quality — one standardized metadata block for every report PDF, so record count,
 * scope/filter summary, language, classification, and generated-by are consistently present
 * across generators (previously each carried an ad-hoc subset via {@code coverHero}).
 *
 * <p>Rendered as a borderless key/value grid (via {@link PdfTheme#metadataGrid()}) plus a
 * confidentiality notice, placed just under the cover hero.
 */
public record ReportMetadata(
    String module,          // e.g. "ERM", "Compliance"
    String exportType,      // e.g. "Risk Register"
    String periodLabel,     // e.g. "As of 2026-07-09"
    String scopeSummary,    // e.g. "All risks (max 1000)"
    String lang,            // "ar" | "en"
    String classification,  // e.g. "Internal"
    int recordCount
) {

    private static final String CONF_EN =
        "CONFIDENTIAL — for internal governance use. Distribution outside the organisation requires approval.";
    private static final String CONF_AR =
        "سرّي — للاستخدام الداخلي في الحوكمة. يتطلب التوزيع خارج المنظمة موافقة مسبقة.";

    /** Render the standard metadata grid + confidentiality notice into {@code doc}. */
    public void renderInto(Document doc, String generatedBy) throws DocumentException {
        boolean ar = "ar".equalsIgnoreCase(lang);
        // RTL-aware grid — mirrors the label/value columns and shapes the Arabic
        // labels (the plain grid shipped disconnected RTL text once).
        PdfPTable g = PdfTheme.metadataGrid(ar);
        PdfTheme.addMetaCell(g, ar ? "الوحدة" : "Module", nz(module));
        PdfTheme.addMetaCell(g, ar ? "نوع التقرير" : "Report type", nz(exportType));
        PdfTheme.addMetaCell(g, ar ? "الفترة" : "Period", nz(periodLabel));
        PdfTheme.addMetaCell(g, ar ? "النطاق" : "Scope", nz(scopeSummary));
        PdfTheme.addMetaCell(g, ar ? "عدد السجلات" : "Records", String.valueOf(recordCount));
        PdfTheme.addMetaCell(g, ar ? "اللغة" : "Language", ar ? "العربية" : "English");
        PdfTheme.addMetaCell(g, ar ? "التصنيف" : "Classification", nz(classification));
        PdfTheme.addMetaCell(g, ar ? "أُنشئ بواسطة" : "Generated by", generatedBy == null || generatedBy.isBlank() ? "system" : generatedBy);
        doc.add(g);

        PdfTheme.line(doc, ar ? CONF_AR : CONF_EN, PdfFonts.small(8), ar, 8, 6);
    }

    private static String nz(String s) { return s == null || s.isBlank() ? "—" : s; }
}
