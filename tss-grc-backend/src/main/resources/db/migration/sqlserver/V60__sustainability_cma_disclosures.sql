-- V60 — CMA Articles 91–94 Disclosure Matrix (Sustainability · slice 6)
--
-- Promotes the 11 canonical CMA disclosure items from a static frontend
-- constant (esg.ts/CMA_ARTICLES) to a real entity with disclosure
-- lifecycle, gap tracking, owner + reviewer, and an auditable trail of
-- last-reviewed timestamps.
--
-- Composition with V58 (Corrective Actions): a Partial or Not Disclosed
-- item that fails Rule 6 (no evidence) raises a CA-SUST-* record via
-- source_type='CMA_DISCLOSURE' / source_ref='{year}-CMA-{article}{clause}'.
-- The V58 seed already has CA-SUST-006 (Art 91) and CA-SUST-007 (Art 93)
-- targeting this entity — they'll now resolve to real rows.
--
-- Status set:
--   DISCLOSED         — full disclosure with evidence attached
--   PARTIAL           — disclosure exists but is incomplete (Rule 5: gap required)
--   NOT_DISCLOSED     — missing entirely (Rule 5: gap required)
--   NOT_APPLICABLE    — formally excluded — must record rationale
--   UNDER_REVIEW      — reviewer assessing the disclosure quality
--   EVIDENCE_REQUIRED — disclosed but evidence_ref empty (Rule 6 auto-tag)
--
-- Service-layer rules:
--   Rule 5 — PARTIAL or NOT_DISCLOSED requires gap_description_en or _ar.
--   Rule 6 — DISCLOSED/PARTIAL with empty evidence_ref auto-tagged as
--            EVIDENCE_REQUIRED on save; aggregate readiness reflects this.

SET QUOTED_IDENTIFIER ON;
SET NOCOUNT ON;
GO

IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = N'cma_disclosure' AND schema_id = SCHEMA_ID('sust'))
BEGIN
    CREATE TABLE sust.cma_disclosure (
        id                       BIGINT IDENTITY(1,1) PRIMARY KEY,
        organisation_id          BIGINT        NOT NULL,
        external_id              NVARCHAR(64)  NULL,

        reporting_year           SMALLINT      NOT NULL,
        article                  NVARCHAR(10)  NOT NULL,    -- "91", "92", "93", "94"
        clause                   NVARCHAR(10)  NULL,        -- "(a)", "(b)", "(c)", "(d)"
        -- Composite display label, e.g. "Art. 91(a)" — generated by service.

        title_en                 NVARCHAR(255) NOT NULL,
        title_ar                 NVARCHAR(255) NULL,

        requirement_en           NVARCHAR(MAX) NULL,
        requirement_ar           NVARCHAR(MAX) NULL,

        -- DISCLOSED | PARTIAL | NOT_DISCLOSED | NOT_APPLICABLE | UNDER_REVIEW | EVIDENCE_REQUIRED
        disclosure_status        NVARCHAR(30)  NOT NULL DEFAULT N'UNDER_REVIEW',

        evidence_ref             NVARCHAR(255) NULL,
        evidence_owner           NVARCHAR(255) NULL,
        responsible_department   NVARCHAR(120) NULL,

        -- Required when status ∈ {PARTIAL, NOT_DISCLOSED} (Rule 5).
        gap_description_en       NVARCHAR(MAX) NULL,
        gap_description_ar       NVARCHAR(MAX) NULL,

        -- Pointer to a sust.corrective_action raised from this gap.
        linked_capa_id           BIGINT        NULL,

        report_section_reference NVARCHAR(120) NULL,        -- e.g. "Annual Report 2025 §3.4"

        reviewer_name            NVARCHAR(255) NULL,
        reviewer_email           NVARCHAR(255) NULL,
        last_reviewed_at         DATETIME2     NULL,
        approval_status          NVARCHAR(30)  NULL,        -- PENDING | APPROVED | REJECTED
        approved_by              NVARCHAR(255) NULL,
        approved_at              DATETIME2     NULL,

        notes                    NVARCHAR(MAX) NULL,

        is_deleted               BIT           NOT NULL DEFAULT 0,
        created_at               DATETIME2     NOT NULL DEFAULT SYSUTCDATETIME(),
        created_by               NVARCHAR(100) NULL,
        updated_at               DATETIME2     NULL,
        updated_by               NVARCHAR(100) NULL,

        CONSTRAINT ck_cma_status CHECK (disclosure_status IN (
            N'DISCLOSED', N'PARTIAL', N'NOT_DISCLOSED', N'NOT_APPLICABLE',
            N'UNDER_REVIEW', N'EVIDENCE_REQUIRED')),
        CONSTRAINT ck_cma_article CHECK (article IN (N'91', N'92', N'93', N'94')),
        CONSTRAINT ck_cma_approval CHECK (approval_status IS NULL OR approval_status IN
            (N'PENDING', N'APPROVED', N'REJECTED'))
    );

    -- One row per (org, year, article+clause). Different reporting years
    -- get separate rows so the matrix is auditable year over year.
    CREATE UNIQUE INDEX uq_cma_org_year_article ON sust.cma_disclosure(
        organisation_id, reporting_year, article, clause
    ) WHERE is_deleted = 0;

    CREATE INDEX ix_cma_org_year      ON sust.cma_disclosure(organisation_id, reporting_year);
    CREATE INDEX ix_cma_org_status    ON sust.cma_disclosure(organisation_id, disclosure_status);
END
GO

