package com.tss.grc.security;

import com.tss.grc.module.privacy.entity.DataBreach;
import com.tss.grc.support.GuardExpressions;
import jakarta.persistence.Column;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * F2-285 — the BREACH end of the cyber → PDPL bridge is on the wire, and stays
 * read-only there.
 *
 * <h2>The finding</h2>
 *
 * <p>[[F2-281]] mapped the incident end of this bridge. The breach end — five
 * columns on {@code privacy.data_breaches} — was written by the same single writer
 * in native SQL and, measured 2026-08-22, read by <b>nothing</b>: zero references
 * anywhere in the backend or the frontend outside {@code CyberPdplBridgeService}.
 * Populated on 2 of 17 rows in dev and 3 of 18 in prod.
 *
 * <p>The bridge's own audit line has always claimed the link is
 * <b>bidirectional</b> — <i>"DataBreach … created and bidirectionally linked to
 * incident INC-00001"</i>. It writes both directions; only one was readable. After
 * F2-281 the asymmetry became visible: an incident carries
 * {@code linkedDataBreachCode} on its wire and a breach could name nothing. Nor
 * could the bridge log answer it — all three of its finders key on
 * {@code cyberIncidentId} and none on {@code dataBreachId}, so a report keyed by
 * incident cannot answer a question asked from a breach ([[F2-178]]).
 *
 * <h2>Why read-only is required here rather than preferred</h2>
 *
 * <p>⚠⚠ This register's endpoints <b>bind the entity</b>:
 * {@code createBreach(@RequestBody DataBreach req)}. A writable mapping would let
 * any caller forge <i>"this breach was auto-generated from cyber incident N"</i> —
 * a provenance claim on a PDPL Article 20 statutory record.
 * {@code ServerOwnedFieldsModule} covers {@code BaseEntity}'s nine fields and
 * cannot help.
 *
 * <p>🔑 {@code PrivacyService#createBreach} already hand-scrubs four fields for
 * exactly this reason, and its javadoc quotes F2-215's headline — <i>"fixing the
 * field you noticed leaves the remainder looking covered, because the mechanism
 * that covers them is visibly present."</i> These five ARE that remainder, and
 * they were invisible only because they were unmapped: mapping them the naive way
 * would have created the defect that comment warns about.
 */
class BreachProvenanceWireContractTest {

    /** The five bridge columns, and the entity field each is mapped by. */
    private static final Map<String, String> BRIDGE_COLUMNS = new LinkedHashMap<>();
    static {
        BRIDGE_COLUMNS.put("auto_generated",               "autoGenerated");
        BRIDGE_COLUMNS.put("auto_generation_rule",         "autoGenerationRule");
        BRIDGE_COLUMNS.put("auto_generated_at",            "autoGeneratedAt");
        BRIDGE_COLUMNS.put("source_cyber_incident_id",     "sourceCyberIncidentId");
        BRIDGE_COLUMNS.put("source_cyber_incident_number", "sourceCyberIncidentNumber");
    }

    private static final Path SERVICE = Path.of(
            "src", "main", "java", "com", "tss", "grc", "module", "privacy",
            "service", "PrivacyService.java");
    private static final Path ENTITY = Path.of(
            "src", "main", "java", "com", "tss", "grc", "module", "privacy",
            "entity", "DataBreach.java");
    private static final Path API_TS = Path.of(
            "..", "tss-grc-ui-v2", "src", "lib", "api.ts");

    /**
     * Comments stripped before any scan. Load-bearing here: this entity's new
     * javadoc quotes {@code createBreach}'s scrub list and the shapes it replaced,
     * so reading raw source counts the epitaph as the corpse ([[F2-193]]).
     */
    private static String code(Path p) throws IOException {
        return GuardExpressions.stripComments(
                Files.readString(p, StandardCharsets.UTF_8));
    }

    private static int count(Pattern p, String s) {
        Matcher m = p.matcher(s);
        int n = 0;
        while (m.find()) n++;
        return n;
    }

    // ─── the mapping ────────────────────────────────────────────────────────

    /** By reflection, never a source regex — an annotation's attributes cannot be misread. */
    @Test
    void everyBridgeColumnIsMappedReadOnly() {
        List<String> problems = new ArrayList<>();
        for (Map.Entry<String, String> e : BRIDGE_COLUMNS.entrySet()) {
            Field f;
            try {
                f = DataBreach.class.getDeclaredField(e.getValue());
            } catch (NoSuchFieldException nsf) {
                problems.add(e.getValue() + " — not declared, so column " + e.getKey()
                        + " is off the wire again");
                continue;
            }
            Column c = f.getAnnotation(Column.class);
            if (c == null) {
                problems.add(e.getValue() + " — no @Column");
                continue;
            }
            if (!e.getKey().equals(c.name())) {
                problems.add(e.getValue() + " — maps " + c.name() + ", expected " + e.getKey());
            }
            if (c.insertable()) {
                problems.add(e.getValue() + " — insertable, and this register's create BINDS "
                        + "THE ENTITY, so a caller could forge the provenance");
            }
            if (c.updatable()) {
                problems.add(e.getValue() + " — updatable; the bridge owns these writes");
            }
        }
        assertThat(problems)
                .as("F2-285: the five cyber-bridge columns are mapped read-only")
                .isEmpty();
    }

    @Test
    void noBridgeColumnHasASetter() {
        List<String> found = new ArrayList<>();
        for (String field : BRIDGE_COLUMNS.values()) {
            String setter = "set" + Character.toUpperCase(field.charAt(0)) + field.substring(1);
            for (var m : DataBreach.class.getMethods()) {
                if (m.getName().equals(setter)) found.add(setter);
            }
        }
        assertThat(found)
                .as("F2-285: a setter over a non-updatable column compiles, runs and "
                    + "silently does nothing — F2-184's decoy, and suppressing it makes "
                    + "the write a compile error instead")
                .isEmpty();
    }

    /** Anti-vacuity: the getters must exist, or every leg above passes over nothing. */
    @Test
    void everyBridgeColumnIsReadable() {
        List<String> missing = new ArrayList<>();
        for (String field : BRIDGE_COLUMNS.values()) {
            String suffix = Character.toUpperCase(field.charAt(0)) + field.substring(1);
            boolean ok = false;
            for (var m : DataBreach.class.getMethods()) {
                if (m.getName().equals("get" + suffix) || m.getName().equals("is" + suffix)) ok = true;
            }
            if (!ok) missing.add(field);
        }
        assertThat(missing).as("F2-285: reading is the whole point of the mapping").isEmpty();
        assertThat(BRIDGE_COLUMNS).hasSize(5);
    }

    // ─── one predicate ──────────────────────────────────────────────────────

    /**
     * Three surfaces ask "did the bridge raise this breach?" — the detail page, and
     * the console and register beside it. F2-282 measured what a second copy of a
     * governance predicate costs, so the comparison lives in one place.
     *
     * <p>Scoped to a comparison against a numeric literal: {@code != null} is a null
     * check, not a second opinion, and a pattern loose enough to match it would fail
     * on the correct code — the mistake F2-281's equivalent leg made on its first
     * draft ([[F2-214]]).
     */
    @Test
    void theProvenanceIsComparedInExactlyOnePlace() throws IOException {
        Pattern comparison = Pattern.compile(
                "(?:get)?[Aa]utoGenerated(?:\\(\\))?\\s*(?:!=|==|>|<)\\s*\\d");

        String entity = code(ENTITY);
        assertThat(count(comparison, entity))
                .as("F2-285: DataBreach#isBridgeRaised is the one comparison")
                .isEqualTo(1);
        assertThat(entity)
                .as("F2-285: and it is reachable as a named predicate")
                .containsPattern("boolean\\s+isBridgeRaised\\s*\\(");
        assertThat(count(comparison, code(SERVICE)))
                .as("F2-285: PrivacyService must ask isBridgeRaised(), never compare the "
                    + "column — that is how two readers of one fact drift apart")
                .isZero();
    }

    /**
     * The scrub list stays. F2-231 added it and its javadoc is what identified these
     * five as the remainder; a slice that "tidies" it away removes the reason this
     * mapping had to be read-only.
     */
    @Test
    void theCreateStillScrubsTheFieldsItAlreadyOwned() throws IOException {
        String svc = code(SERVICE);
        for (String scrubbed : List.of("setSdaiaSubmittedAt(null)",
                                       "setSdaiaSubmissionRef(null)",
                                       "setPdpcNotifiedAt(null)")) {
            assertThat(svc)
                    .as("F2-285/F2-231: createBreach must keep scrubbing %s", scrubbed)
                    .contains(scrubbed);
        }
        // ⚠⚠ This leg's first draft asserted the OPPOSITE — that the create must NOT
        // scrub the five, "because they are unwritable so a scrub would be decoration
        // (F2-184)". The live probe refuted it: the read-only mapping stops the values
        // being STORED and does not stop them being ECHOED, because createBreach
        // returns `breachRepo.save(req)` — the caller's own deserialised instance. A
        // POST claiming autoGenerated: 1 came back 201 saying so, over a row whose
        // columns were (0, null, null, null, null).
        //
        // 🔑 Unwritable to the database is not absent from the response.
        //
        // The scrub is on the ENTITY, not here: the five have @Setter(AccessLevel.NONE)
        // so no service CAN clear them, and a @PrePersist fires on the same instance
        // the service returns. So what this leg holds is that the service has not
        // grown a redundant second mechanism (F2-190).
        for (String field : BRIDGE_COLUMNS.values()) {
            String setter = "set" + Character.toUpperCase(field.charAt(0)) + field.substring(1);
            assertThat(svc)
                    .as("F2-285: %s does not exist — the entity's @PrePersist owns this, "
                        + "and a second mechanism here would be the one to drift", setter)
                    .doesNotContain(setter);
        }
    }

    /**
     * The half the read-only mapping does not cover, asserted structurally.
     *
     * <p>Probed live: a create claiming {@code autoGenerated: 1} and
     * {@code sourceCyberIncidentNumber: "INC-FORGED"} returned 201 echoing both, over
     * a row that stored neither. The {@code @PrePersist} clears the instance, so the
     * response describes the row.
     *
     * <p>It cannot affect the bridge, and that is why it is safe:
     * {@code CyberPdplBridgeService} writes both ends in native SQL and never persists
     * an entity, so the only rows this touches are Hibernate-created ones.
     */
    @Test
    void theEntityClearsItsOwnProvenanceOnPersist() throws IOException {
        String entity = code(ENTITY);

        assertThat(entity)
                .as("F2-285: a Hibernate-created breach must not echo a provenance it "
                    + "cannot store")
                .containsPattern("@PrePersist");

        int at = entity.indexOf("@PrePersist");
        String body = entity.substring(at);
        body = body.substring(0, body.indexOf("\n    }"));
        for (String field : BRIDGE_COLUMNS.values()) {
            assertThat(body)
                    .as("F2-285: the @PrePersist must clear %s too — clearing four of five "
                        + "is F2-215's remainder problem in the fix itself", field)
                    .containsPattern(field + "\\s*=\\s*null");
        }

        // And the bridge must stay native SQL, or the @PrePersist would start
        // erasing the provenance it exists to protect.
        String bridge = code(Path.of("src", "main", "java", "com", "tss", "grc",
                "module", "privacy", "bridge", "service", "CyberPdplBridgeService.java"));
        assertThat(bridge)
                .as("F2-285: the bridge writes the provenance in native SQL. If it ever "
                    + "persists a DataBreach entity instead, the @PrePersist above will "
                    + "silently erase exactly the fields it is trying to set.")
                .doesNotContain("breachRepo.save")
                .containsPattern("INSERT INTO privacy\\.data_breaches");
    }

    // ─── the frontend half (the F2-193 pair) ────────────────────────────────

    /**
     * The backend half cannot tell a real DTO property from a plausible string and
     * the frontend half cannot resolve a Java field, so both are needed.
     * Comment-stripped, because F2-280's equivalent leg was satisfied by its own
     * JSDoc and F2-281's had to be rewritten for the same reason.
     */
    @Test
    void theFrontendWireDeclaresTheProvenanceOnTheResponseOnly() throws IOException {
        String ts = code(API_TS);
        String dto = slice(ts, "export interface PrivacyBreachDto {", "}");

        assertThat(dto)
                .as("F2-285: the breach's wire carries its provenance")
                .containsPattern("autoGenerated\\s*\\??\\s*:\\s*number")
                .containsPattern("sourceCyberIncidentNumber\\s*\\??\\s*:\\s*string")
                .containsPattern("sourceCyberIncidentId\\s*\\??\\s*:\\s*number");

        // No request type may declare them: a field the bound type does not declare
        // can never arrive (F2-233), which is stronger than any guard in the service.
        for (String iface : List.of("PrivacyBreachRequest", "SdaiaSubmissionRequest")) {
            int i = ts.indexOf("export interface " + iface + " {");
            if (i < 0) continue;
            String body = slice(ts, "export interface " + iface + " {", "}");
            for (String f : List.of("autoGenerated", "autoGenerationRule",
                                    "sourceCyberIncident")) {
                assertThat(body)
                        .as("F2-285: %s must not let a caller supply %s", iface, f)
                        .doesNotContain(f);
            }
        }
    }

    private static String slice(String s, String open, String close) {
        int i = s.indexOf(open);
        assertThat(i).as("F2-285: anchor %s must exist in api.ts", open).isNotNegative();
        int j = s.indexOf("\n" + close, i);
        assertThat(j).as("F2-285: %s must be closed", open).isGreaterThan(i);
        return s.substring(i, j);
    }

    /**
     * The stripper, with the two-pass form as the negative control — never a
     * reordered alternation, which is an equivalent mutant ([[F2-211]]).
     */
    @Test
    void theStripperIsSound() {
        String src = "// retired: autoGenerated != 0 -- see /* the old note\n"
                   + "boolean b = getAutoGenerated() != null;\n"
                   + "/* autoGenerated == 1 */\n";

        String stripped = GuardExpressions.stripComments(src);
        assertThat(stripped).contains("getAutoGenerated()");
        assertThat(stripped).doesNotContain("retired");
        assertThat(stripped).doesNotContain("!= 0");
        assertThat(stripped).doesNotContain("== 1");

        String twoPass = src.replaceAll("/\\*[\\s\\S]*?\\*/", "")
                            .replaceAll("(?<!:)//[^\\n]*", "");
        assertThat(twoPass)
                .as("the two-pass form is what corrupts the source")
                .doesNotContain("getAutoGenerated()");
    }
}
