/**
 * Saudi GRC platform workflow catalog — every workflow listed in the
 * implementation prompt's §7.1-§7.6 sections, plus the cross-module
 * workflows from §7.6 + §22 master engine. The route is the wizard
 * page; the `status` field tells the Workflow Hub whether the wizard is
 * shipped, partially shipped, or still on the backlog.
 *
 * <p>This is the single source of truth used by both the Workflow Hub
 * index page AND the per-module pages that surface "Start a new …"
 * buttons. Adding a new wizard means: (1) ship the wizard page,
 * (2) flip status from 'PLANNED' to 'AVAILABLE' here.
 */
export type WorkflowStatus = 'AVAILABLE' | 'PARTIAL' | 'PLANNED';

export type WorkflowModule =
  | 'ERM' | 'BCM' | 'SCM' | 'NCA' | 'PDPL'
  | 'COMPLIANCE' | 'EVIDENCE' | 'INCIDENT' | 'GOVERNANCE';

export interface WorkflowDef {
  /** Stable identifier — referenced from the WorkflowHub URL. */
  id: string;
  module: WorkflowModule;
  titleEn: string;
  titleAr: string;
  /** One-line description shown on the catalog card. */
  descEn: string;
  descAr: string;
  /** Wizard URL — `null` for PLANNED entries. */
  route: string | null;
  status: WorkflowStatus;
  /** Lucide icon shown on the catalog card. */
  Icon: LucideIcon;
  /** Number of steps (when known) — drives the chip on the catalog card. */
  steps?: number;
  /** Saudi regulatory anchor — shown as a chip ("PDPL Art. 23", "NCA ECC §1-3"). */
  anchor?: string;
}

